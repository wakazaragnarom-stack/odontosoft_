ALTER TABLE public.usuario
    ADD COLUMN IF NOT EXISTS ultimo_acceso timestamp without time zone;

ALTER TABLE public.usuario
    ALTER COLUMN correo TYPE varchar(100);

ALTER TABLE public.usuario
    ALTER COLUMN contrasena TYPE varchar(255);

-- La aplicación autentica con hash en usuario.contrasena.
-- No se elimina paciente.contrasena_plano porque el modelo actual todavía
-- lo conserva por compatibilidad histórica; no debe utilizarse como secreto.

UPDATE public.usuario
SET estado = 'Activo'
WHERE estado IS NULL OR btrim(estado) = '';

ALTER TABLE public.usuario
    ALTER COLUMN estado SET DEFAULT 'Activo';

ALTER TABLE public.usuario
    ALTER COLUMN estado SET NOT NULL;

ALTER TABLE public.usuario
    ALTER COLUMN correo TYPE varchar(100);

-- ============================================================
-- 2. ODONTÓLOGO: ampliar longitudes del modelo actual
-- ============================================================

ALTER TABLE public.odontologo
