-- ============================================================
-- 4. CITA: estado por defecto compatible con el backend
-- ============================================================

UPDATE public.cita
SET estado = 'Pendiente'
WHERE estado IS NULL OR estado = 'En Espera';

ALTER TABLE public.cita
    ALTER COLUMN estado SET DEFAULT 'Pendiente';

-- ============================================================
-- 5. SERVICIO: el backend usa paciente_id, no id_paciente
-- ============================================================

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'servicio'
          AND column_name = 'id_paciente'
    )
    AND NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'servicio'
          AND column_name = 'paciente_id'
    ) THEN
        ALTER TABLE public.servicio RENAME COLUMN id_paciente TO paciente_id;
    END IF;
END $$;

-- El esquema legacy hacía que tratamiento dependiera de una sola cita.
-- El backend actual modela cita <-> tratamiento como relación N:N mediante
-- cita_tratamiento, por lo que se preservan primero esos vínculos y luego se
-- elimina la dependencia antigua.

INSERT INTO public.cita_tratamiento (id_cita, id_tratamiento)
SELECT t.id_cita, t.id_tratamiento
FROM public.tratamiento AS t
WHERE t.id_cita IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM public.cita_tratamiento AS ct
      WHERE ct.id_cita = t.id_cita
        AND ct.id_tratamiento = t.id_tratamiento
  );

ALTER TABLE public.tratamiento
    DROP CONSTRAINT IF EXISTS fk_tratamiento_cita;

ALTER TABLE public.tratamiento
    DROP COLUMN IF EXISTS id_cita;

-- El servicio actual no depende directamente de tratamiento.id; usa los
-- campos de presentación definidos por el backend.
ALTER TABLE public.servicio
    DROP CONSTRAINT IF EXISTS servicio_id_tratamiento_fkey;

ALTER TABLE public.servicio
    DROP COLUMN IF EXISTS id_tratamiento;

-- ============================================================
-- 6. PASSWORD RESET: tabla requerida por PasswordResetToken
-- ============================================================

CREATE TABLE IF NOT EXISTS public.password_reset_token (
    id_token integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token varchar(255) NOT NULL UNIQUE,
    id_usuario integer NOT NULL,
    fecha_creacion timestamp without time zone NOT NULL,
    fecha_expiracion timestamp without time zone NOT NULL,
    usado boolean NOT NULL DEFAULT false,
    CONSTRAINT password_reset_token_usuario_fkey
        FOREIGN KEY (id_usuario)
        REFERENCES public.usuario(id_usuario)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_password_reset_token_id_token
    ON public.password_reset_token (id_token);

CREATE INDEX IF NOT EXISTS ix_password_reset_token_token
    ON public.password_reset_token (token);

CREATE INDEX IF NOT EXISTS ix_password_reset_token_id_usuario
    ON public.password_reset_token (id_usuario);

-- ============================================================
-- 7. ÍNDICES DE FK utilizados frecuentemente por el backend
-- ============================================================

CREATE INDEX IF NOT EXISTS ix_cita_id_paciente
    ON public.cita (id_paciente);

CREATE INDEX IF NOT EXISTS ix_cita_id_odontologo
