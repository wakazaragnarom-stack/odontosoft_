-- OdontoSoft - sincronización de la base PostgreSQL antigua con el backend actual
--
-- Origen esperado: dump legacy de ProyectoApi / OdontoSoft.
-- IMPORTANTE: ejecutar sobre una COPIA/backup de la base antes de producción.
-- Esta migración NO crea tablas automáticamente desde SQLAlchemy; sincroniza
-- explícitamente el esquema existente y conserva los datos que son compatibles.

